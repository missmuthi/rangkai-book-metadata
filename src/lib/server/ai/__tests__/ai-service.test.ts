import { describe, it, expect, vi, beforeEach } from "vitest";

// Mock SvelteKit env import and set env var to bypass missing API key early exit
vi.mock("$env/dynamic/private", () => ({ env: { GROQ_API_KEY: "TEST_KEY" } }));

// Mock the ai and google model dependencies
vi.mock("ai", async () => ({
  generateObject: vi.fn(),
  generateText: vi.fn(),
}));
vi.mock("@ai-sdk/openai", async () => ({
  createOpenAI: (opts: unknown) => (name: string) => ({ model: name, opts }),
}));

import { generateObject, generateText } from "ai";
import { aiService } from "../index";

describe("aiService.cleanMetadata", () => {
  beforeEach(() => {
    (generateObject as any).mockReset();
  });

  it("applies cleaned fields and returns DDC/LCC if generated by AI", async () => {
    const mockAIObject = {
      title: "Clean Code",
      authors: ["Robert C. Martin"],
      publisher: "New York : Prentice Hall, 2008",
      description: "A modern software engineering guide.",
      ddc: "005.133",
      lcc: "QA76.73.J38",
      changes: ["Generated DDC: 005.133", "Generated LCC: QA76.73.J38"],
    };

    (generateObject as any).mockResolvedValue({ object: mockAIObject });

    const result = await aiService.cleanMetadata({
      title: "Clean Code" as any,
    } as any);

    expect(result.ddc).toBe("005.133");
    expect(result.lcc).toBe("QA76.73.J38");
    expect(result._changes).toEqual(mockAIObject.changes);
    expect(generateObject as any).toHaveBeenCalled();
  });

  it("returns aiWarning when generateObject throws", async () => {
    (generateObject as any).mockRejectedValue(new Error("AI down"));

    const result = await aiService.cleanMetadata({ title: "Test" } as any);

    expect(result.aiWarning).toBe("AI cleaning service unavailable");
  });

  it("falls back to generateText when model does not support json_schema", async () => {
    (generateObject as any).mockRejectedValue(
      new Error("This model does not support response format `json_schema`"),
    );

    const textOutput = JSON.stringify({
      title: "Fallback Title",
      authors: ["Fallback Author"],
      publisher: "Fallback : Publisher, 2024",
      description: "Fallback description.",
      ddc: "005.100",
      lcc: "QA76.1",
      changes: ["Generated DDC: 005.100"],
    });

    (generateText as any).mockResolvedValue({ output_text: textOutput });

    const result = await aiService.cleanMetadata({ title: "Test" } as any);
    expect(result.title).toBe("Fallback Title");
    expect(result.ddc).toBe("005.100");
    expect(result._changes).toEqual(["Generated DDC: 005.100"]);
    expect(generateText as any).toHaveBeenCalled();
  });
});
